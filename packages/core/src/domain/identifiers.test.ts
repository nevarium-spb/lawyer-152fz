import { describe, expect, it } from 'vitest';

import { isValidInn, isValidOgrn } from './identifiers';

describe('ИНН', () => {
  it.each(['7707083893', '1234567894', '500100732259', '123456789047'])('%s — корректен', (inn) => {
    expect(isValidInn(inn)).toBe(true);
  });

  it.each([
    ['7707083894', 'неверная контрольная цифра (10)'],
    ['123456789048', 'неверная последняя цифра (12)'],
    ['123456789037', 'неверная предпоследняя цифра (12)'],
    ['12345', 'неверная длина'],
    ['77070838a3', 'не цифры'],
    ['', 'пусто'],
  ])('%s — некорректен: %s', (inn) => {
    expect(isValidInn(inn)).toBe(false);
  });
});

describe('ОГРН / ОГРНИП', () => {
  it.each(['1027700132195', '1027700000008', '304500116000157', '304500000000009'])(
    '%s — корректен',
    (ogrn) => {
      expect(isValidOgrn(ogrn)).toBe(true);
    },
  );

  it.each([
    ['1027700000009', 'неверная контрольная цифра ОГРН'],
    ['304500000000008', 'неверная контрольная цифра ОГРНИП'],
    ['10277000000', 'неверная длина'],
    ['10277000000O8', 'не цифры'],
  ])('%s — некорректен: %s', (ogrn) => {
    expect(isValidOgrn(ogrn)).toBe(false);
  });
});
