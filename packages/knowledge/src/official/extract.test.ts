import { describe, expect, it } from 'vitest';

import { extractArticles, extractDecreeItems } from './extract';
import type { OfficialParagraph } from './official-html';

const p = (text: string, cls = '', notes: string[] = []): OfficialParagraph => ({
  cls,
  text,
  notes,
});

describe('extractArticles', () => {
  const law = [
    p('О тестовых данных', 'Z'),
    p('Глава 1. Общие положения', 'H'),
    p('Статья 1. Сфера действия', 'H'),
    // Класс P — пометка к статье целиком, а не подпись: разбор не должен на ней обрываться.
    p('(Дополнение статьей - Федеральный закон)', 'P'),
    p('1. Первая часть.'),
    p('1.1. Дробная часть.', '', ['(Дополнение частью)']),
    p('Глава 2. Принципы', 'H'),
    p('Текст между главами не относится к статье.'),
    p('Статья 7.1.', 'H', ['(Утратила силу - Федеральный закон)']),
    p('Статья 13.11. Нарушение', 'H'),
    p('1. Обработка без оснований -'),
    p('влечет наложение штрафа.'),
    p('', '', ['(В редакции Федерального закона)']),
    p('Президент Российской Федерации', 'Y'),
    p('Москва, Кремль'),
  ];

  it('извлекает статьи, отсекает главы и подпись, собирает пометки', () => {
    expect(extractArticles(law)).toEqual([
      {
        number: '1',
        heading: 'Статья 1. Сфера действия',
        text: '1. Первая часть.\n\n1.1. Дробная часть.',
        notes: ['(Дополнение статьей - Федеральный закон)', '(Дополнение частью)'],
      },
      {
        number: '7.1',
        heading: 'Статья 7.1.',
        text: '(Утратила силу - Федеральный закон)',
        notes: ['(Утратила силу - Федеральный закон)'],
      },
      {
        number: '13.11',
        heading: 'Статья 13.11. Нарушение',
        text: '1. Обработка без оснований -\n\nвлечет наложение штрафа.',
        notes: ['(В редакции Федерального закона)'],
      },
    ]);
  });

  it('берёт только указанные статьи', () => {
    expect(extractArticles(law, ['13.11']).map((a) => a.number)).toEqual(['13.11']);
  });
});

describe('extractDecreeItems', () => {
  const decree = [
    p('ПОСТАНОВЛЕНИЕ', 'T'),
    p('1. Утвердить прилагаемое Положение.'),
    p('Председатель Правительства', 'Y'),
    p('ПОЛОЖЕНИЕ об особенностях обработки', 'T'),
    p('I. Общие положения', 'C'),
    p('1. Первый пункт.'),
    p('2. Второй пункт:', '', ['(В редакции)']),
    p('а) подпункт;'),
    p('II. Особенности', 'C'),
    p('3. Третий пункт.'),
    p('____________', 'C'),
    p('Приложение — не пункт.'),
  ];

  it('берёт пункты утверждённого документа, а не самого постановления', () => {
    expect(extractDecreeItems(decree, /^ПОЛОЖЕНИЕ/)).toEqual([
      { number: '1', heading: '', text: '1. Первый пункт.', notes: [] },
      {
        number: '2',
        heading: '',
        text: '2. Второй пункт:\n\nа) подпункт;',
        notes: ['(В редакции)'],
      },
      { number: '3', heading: '', text: '3. Третий пункт.', notes: [] },
    ]);
  });

  it('без заголовка документа — пустой список', () => {
    expect(extractDecreeItems(decree, /^ТРЕБОВАНИЯ/)).toEqual([]);
  });
});
